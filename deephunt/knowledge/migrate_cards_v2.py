#!/usr/bin/env python3
"""One-time migration: upgrade technique cards to the §26 schema.

Adds (additively — nothing removed):
  preconditions, required_state, hypothesis_generator, request_strategy,
  mutation_strategy, expected_signal, positive_oracle, negative_evidence,
  false_positive_rules, followup_experiment, regression_test,
  difficulty_estimate

Defaults are derived from existing fields where possible, else sensible
placeholders. Regenerates the merged knowledge/techniques.yaml.
"""
from __future__ import annotations

import glob
import os
import sys

import yaml

BASE = os.path.dirname(os.path.abspath(__file__))
TECH_DIR = os.path.join(BASE, "techniques")

NEW_FIELDS = {
    "preconditions": list,
    "required_state": list,
    "hypothesis_generator": str,
    "request_strategy": str,
    "mutation_strategy": str,
    "expected_signal": str,
    "positive_oracle": str,
    "negative_evidence": list,
    "false_positive_rules": list,
    "followup_experiment": str,
    "regression_test": str,
    "difficulty_estimate": float,
}

_DEFAULT_FP_RULES = [
    "candidate is not a finding: requires evidence contract satisfaction",
    "kill the benign alternative explicitly before promotion",
    "an invalid control (owner denied) poisons the comparison — re-baseline",
]

_DIFFICULTY_BY_IMPACT = {"critical": 0.7, "high": 0.6, "medium": 0.45, "low": 0.3}


def upgrade(card: dict) -> dict:
    ev = card.get("evidence") or {}
    requires = card.get("requires") or []
    if "preconditions" not in card:
        card["preconditions"] = list(requires) or ["observe the surface first"]
    card.setdefault("required_state", [])
    if "hypothesis_generator" not in card:
        card["hypothesis_generator"] = (
            f"When signals {card.get('signals', [])[:4]} are observed, "
            f"hypothesize: {card.get('name', '')}.")
    card.setdefault("request_strategy",
                    "control/test differential pair across identities or states")
    card.setdefault("mutation_strategy", "semantic mutation of the key parameter")
    card.setdefault("expected_signal",
                    "; ".join(ev.get("positive", [])[:3]) or "security-relevant difference")
    if "positive_oracle" not in card:
        card["positive_oracle"] = (ev.get("positive") or ["differential_confirmed"])[0]
    if "negative_evidence" not in card:
        card["negative_evidence"] = list(ev.get("negative", []))
    card.setdefault("false_positive_rules", list(_DEFAULT_FP_RULES))
    card.setdefault("followup_experiment",
                    "; ".join(card.get("followups", [])[:2]) or "validate with independent verifier")
    card.setdefault("regression_test", "replay control/test pair; expect oracle HELD")
    if "difficulty_estimate" not in card:
        hint = str(card.get("impact_hint", "")).lower()
        card["difficulty_estimate"] = next(
            (v for k, v in _DIFFICULTY_BY_IMPACT.items() if k in hint), 0.5)
    return card


def main() -> int:
    total = 0
    merged = []
    for path in sorted(glob.glob(os.path.join(TECH_DIR, "*.yaml"))):
        docs = yaml.safe_load(open(path)) or []
        upgraded = [upgrade(c) for c in docs if isinstance(c, dict)]
        total += len(upgraded)
        merged.extend(upgraded)
        header = (f"# DEEPHUNT technique cards — {os.path.basename(path)[:-5]} domain\n"
                  f"# Schema v2 (§26): preconditions/required_state/hypothesis_generator/\n"
                  f"# request_strategy/mutation_strategy/expected_signal/positive_oracle/\n"
                  f"# negative_evidence/false_positive_rules/followup_experiment/\n"
                  f"# regression_test/difficulty_estimate. {len(upgraded)} cards.\n\n")
        body = yaml.safe_dump(upgraded, sort_keys=False, allow_unicode=True,
                              default_flow_style=False)
        open(path, "w").write(header + body)
        print(f"{os.path.basename(path)}: {len(upgraded)} cards upgraded")
    merged_path = os.path.join(BASE, "techniques.yaml")
    open(merged_path, "w").write(
        "# MERGED — generated by knowledge/migrate_cards_v2.py from knowledge/techniques/*.yaml\n"
        "# Do not edit by hand; edit the domain files and re-run the migration.\n\n"
        + yaml.safe_dump(merged, sort_keys=False, allow_unicode=True,
                          default_flow_style=False))
    print(f"merged techniques.yaml: {total} cards")
    return 0


if __name__ == "__main__":
    sys.exit(main())
